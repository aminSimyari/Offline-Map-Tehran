// Get station by ID
export function getStationById(id: number): MetroStation | undefined {
  return tehranStations.find((s) => s.id === id)
}

// Get line stations as coordinates
export function getLineCoordinates(lineId: number): [number, number][] {
  const line = tehranLines.find((l) => l.id === lineId)
  if (!line) return []

  return line.stations
    .map((stationId) => {
      const station = getStationById(stationId)
      return station ? ([station.lng, station.lat] as [number, number]) : null
    })
    .filter((coord): coord is [number, number] => coord !== null)
}
